/**
 * Do we install here?
 * Returns null for anything that isn't a complete 5-digit ZIP — that's
 * "not finished typing", not a refusal. Only a real 5-digit ZIP that misses
 * the list is a no: the gazetteer covers every ZCTA in the country, so
 * absence from it is an answer rather than a gap.
 */
export function inServiceArea(zip) {
  const z = String(zip ?? '').replace(/\D/g, '')
  return z.length === 5 ? ZIPS.has(z) : null
}

